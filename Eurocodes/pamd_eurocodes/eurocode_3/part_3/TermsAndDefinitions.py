try:
    from tad import TAD
except ImportError:
    from pamd_eurocodes.tad import TAD

# Terms and definitions used in EN 1993-3 (Towers, Masts and Chimneys)

LatticeTower = TAD(
    "lattice tower",
    "A self-supporting space framework tower structure with three, four or more polygonal sides composed of lattice truss members."
)

GuyedMast = TAD(
    "guyed mast",
    "A slender vertical structural column or mast supported at one or more levels by inclined guy cables anchored to ground foundations."
)

Chimney = TAD(
    "chimney",
    "A vertical cantilever cylindrical or conical shell structure designed to discharge flue gases, emissions, or exhaust into the atmosphere."
)

GuyRope = TAD(
    "guy rope",
    "A structural stay wire rope, spiral strand, or locked-coil cable used to provide lateral support and stability to a guyed mast."
)

Insulator = TAD(
    "insulator",
    "A non-conducting electrical isolation component inserted in series into guy cables or tower legs to prevent electrical conductivity."
)

Galloping = TAD(
    "galloping",
    "A low-frequency, large-amplitude cross-wind aeroelastic instability occurring on non-circular cross-sections or ice-coated cables."
)

VortexShedding = TAD(
    "vortex shedding",
    "Periodic alternate shedding of vortices from opposite sides of a slender bluff body causing cross-wind oscillatory dynamic forces at resonance (lock-in)."
)

AerodynamicDamping = TAD(
    "aerodynamic damping",
    "The component of total damping generated by the relative aerodynamic drag and pressure forces between the oscillating structure and the surrounding fluid."
)

RainWindInducedVibration = TAD(
    "rain-wind induced vibration",
    "Large-amplitude dynamic oscillation of inclined stay cables occurring under simultaneous moderate wind and light-to-medium rain."
)

PatchLoading = TAD(
    "patch loading",
    "Non-uniform spatial wind pressure distribution applied over localized segments or sub-panels of a tower, mast, or chimney."
)
